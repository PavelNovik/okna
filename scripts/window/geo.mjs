export const GEO_FROM = 22
export const GEO_TO = 84

// трек для любого кадра диапазона: линейная интерполяция между ключами + сглаживание 1-2-1
function raw(i) {
  const keys = Object.keys(K).map(Number)
  if (K[i]) return K[i]
  const lo = Math.max(...keys.filter((k) => k < i))
  const hi = Math.min(...keys.filter((k) => k > i))
  const t = (i - lo) / (hi - lo)
  return K[lo].map((v, j) => v + (K[hi][j] - v) * t)
}
export function track(i) {
  const a = raw(Math.max(GEO_FROM, i - 1)), b = raw(i), c = raw(Math.min(GEO_TO, i + 1))
  return b.map((v, j) => 0.25 * a[j] + 0.5 * v + 0.25 * c[j])
}

// мягкая «ступенька» по x: 0 → 1 на отрезке [edge-0.75, edge+0.75]
const ramp = (x, edge) => Math.max(0, Math.min(1, (x - edge + 0.75) / 1.5))

// alpha по столбцу x для кадра i (без учёта строк): просвет — 1, стекло — 0.9, профили — 0
export function columnAlpha(i, x) {
  const [hL, aL, bL, bR, aR, hR] = track(i)
  const glassL = ramp(x, hL + 1.5) * (1 - ramp(x, aL - 1.5))
  const gap = ramp(x, bL + 1.5) * (1 - ramp(x, bR - 1.5))
  const glassR = ramp(x, aR + 1.5) * (1 - ramp(x, hR - 1.5))
  return Math.max(gap, 0.9 * Math.max(glassL, glassR))
}
